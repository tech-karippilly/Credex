import { Injectable } from '@nestjs/common';
import PDFDocument from 'pdfkit';
import { COMPANY } from '../../common/constants/company.constants';
import { VoucherResponse } from '../interfaces/voucher-response.interface';
import {
  formatInrAmount,
  formatPaymentModeLabel,
  formatVoucherDate,
} from '../utils/voucher-format.util';

@Injectable()
export class VoucherPdfService {
  async generate(voucher: VoucherResponse): Promise<Buffer> {
    return new Promise((resolve, reject) => {
      const doc = new PDFDocument({ margin: 48, size: 'A4' });
      const chunks: Buffer[] = [];

      doc.on('data', (chunk: Buffer) => chunks.push(chunk));
      doc.on('end', () => resolve(Buffer.concat(chunks)));
      doc.on('error', reject);

      const primary = COMPANY.primaryColor;

      doc
        .fontSize(18)
        .fillColor(primary)
        .text(COMPANY.legalName, { align: 'left' });
      doc
        .fontSize(9)
        .fillColor('#555555')
        .text(`CIN: ${COMPANY.cin} · ${COMPANY.location}`);

      doc.moveDown(1.2);
      doc
        .fontSize(14)
        .fillColor('#00142B')
        .text('PAYMENT VOUCHER', { align: 'center', underline: false });

      doc.moveDown(0.8);
      doc.fontSize(11).fillColor('#00142B');
      doc.text(`Voucher No: ${voucher.voucherNumber}`, { continued: true });
      doc.text(`Date: ${formatVoucherDate(voucher.voucherDate)}`, {
        align: 'right',
      });

      doc.moveDown(0.4);
      doc.text(`Type: ${voucher.voucherType}`);
      doc.text(`Title: ${voucher.title}`);
      if (voucher.description) {
        doc.text(`Description: ${voucher.description}`);
      }
      doc.text(`Paid by: ${voucher.paidBy}`);
      doc.text(`Payee: ${voucher.payee}`);
      doc.text(`Payment mode: ${formatPaymentModeLabel(voucher.paymentMode)}`);
      doc.text(`Amount: ${formatInrAmount(voucher.amount)}`);
      if (voucher.referenceNumber) {
        doc.text(`Reference: ${voucher.referenceNumber}`);
      }
      if (voucher.category?.name) {
        doc.text(`Category: ${voucher.category.name}`);
      }
      doc.text(`Status: ${voucher.status}`);

      doc.moveDown(1.5);
      doc
        .fontSize(9)
        .fillColor('#666666')
        .text(
          `Generated by ${COMPANY.brand} · ${COMPANY.website}`,
          { align: 'center' },
        );

      doc.end();
    });
  }
}
